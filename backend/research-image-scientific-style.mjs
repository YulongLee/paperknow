// Keep scene rules separate from the author's evidence. These rules constrain
// presentation; they must never supply measurements or scientific conclusions.
export function scientificFigureStyle(choice){
 const rules=[
  '学术成图要求：纯白画布、平整清晰的线条、统一字体与线宽、充足外边距。采用二维或必要的轴测表达；避免海报、装饰性光效、渐变背景、厚重阴影和无意义图标。',
  '标注简短且一一对应对象，不遮挡图形或相互重叠。连线起止点明确，箭头只表达真实方向，交叉处避免歧义。主次通过位置、线型与有限的颜色表达，不能只靠红绿区分。',
  '严格遵守作者给定的名称、层级、连接及数值。数据、坐标、单位、图例必须一致；未给出观测值时不得添加统计结论、误差线、显著性星号、性能指标或伪实验图像。',
  '除非作者明确要求，不在图内添加标题、图号、图注、说明段落、拟开展、待补充、示例、软件名称或品牌标识；图注由稿件另行排版。不要把排版指令印在图片里。'
 ];
 const type=choice.id,category=choice.categoryId;
 const exact={

  auto:'依据作者内容选择恰当图种，不用通用研究流程替代专属内容；数值、层级、步骤或空间关系分别选合适表达。',
  flowchart:'流程步骤和条件分支区分；条件用菱形并标明分支条件，所有必要路径连通，不能凭空添加输入或输出。',
  pie:'扇区角度对应同一总体的非负原始数值，合计与图例一致，不使用3D透视，不把互不相关的值组成百分比。',
  tree:'只表达明确的父子包含关系；每个非根节点只有一个父节点，不能产生循环或遗漏层级。',
  treemap:'父子矩形严格嵌套，面积按给定权重分配；纯分类无权重时只表达包含，不显示虚假比例。',
  'horizontal-bar':'水平条长对应实际数值，数值轴包含零，标签与条目一一对应且顺序固定。',
  'pictorial-bar':'用重复且等大的简单符号编码数值，不能以不同图标大小造成面积误导；保留准确的数值轴与分类。',
  radar:'每个指标有清楚的轴、范围和单位，同一指标的各组使用同一尺度，不混用量纲形成虚假的优劣结论。',
  gauge:'明确仪表的单位、上下限及当前值；没有百分比依据不得默认是百分比或自动补造目标。',
  scatter:'每个散点对应一组实际的x/y观测值，坐标单位清楚；不凭空拟合趋势、相关系数、置信区间或聚类。',
  candlestick:'每个时间标签严格对应开盘、收盘、最低、最高；上下影线范围包含开收盘，涨跌用颜色与实空形状同时区别。',
  sankey:'连接宽度对应明确的非负流量，节点输入输出守恒或作者已说明的损耗；不能编造流量或伪造平衡。',
  matrix:'行列标签、单元格与坐标一一对应，区分数值矩阵和概念关系矩阵；不可用随机颜色填充未提供的值。',
  calendar:'日期连续且有效，星期起点、月份与具体日期对齐，颜色对应当天实际数值，缺失日留空。',
  parallel:'每条折线对应同一条观测的所有维度，每维范围与单位清楚；缺失值不能偷偷填零或造数。',
  'mindmap-network':'中心主题、交叉联系与分组明确；允许非树状关联，但不把联想当因果，不重复同一概念节点。',
  network:'每个节点只出现一次，边起止对象与方向明确，无权重关系不得暗示定量强度或伪造重要性。',
  funnel:'阶段顺序与原始数量一致；数值与比例有依据，不强行把非递减数列绘成转化漏斗。',
  path:'路径顺序、分叉、汇合和方向均对应作者说明，避免断路、无依据的回路和错误捷径。',
  river:'同一时间各主题数值对应原始记录，时间序列正确；面积流动表示数值变化而非虚构趋势。',
  journey:'按用户实际阶段展现触点、行为和问题，不凭空生成满意度数值；阶段顺序与参与者清晰。',
  requirement:'需求具有明确标识与验证、派生、满足或包含关系，关系类型须标明，不能用普通流程冒充需求模型。',
  zenuml:'遵守UML交互语义，调用和返回指向实际对象，条件、循环、自调用以及同步消息均准确。',
  class:'类名、属性、方法分区，继承空心三角指向父类，组合菱形位于整体端，关联基数有依据。',
  architecture:'层次、模块、接口与数据流清晰，不能混淆部署关系和逻辑调用，组件名称不重复。',
  timeline:'按时间顺序绘制事件，时间或阶段只用作者提供内容，不添加虚假日期或定量间距。',

  sunburst:'旭日图必须由同心环扇区表示树形层级，父节点的外层子扇区严格落在父扇区的角度范围内；没有权重时只表达分类，不暗示测量占比。',
  chord:'和弦图必须使用圆周上的群组扇区以及扇区之间的带状和弦，不能替换成普通圆形节点网络。带宽仅在作者给出权重时编码数值；无权重时用等宽带表示定性关系。',
  sequence:'使用标准时序图：参与者置于顶部，垂直生命线，消息按时间自上而下排列；调用实线、返回虚线，失败分支使用有条件的分支框。箭头必须指向实际接收者。',
  state:'使用标准状态图：状态只出现一次，起点为实心圆，终点为同心圆；每条转换边对应明确事件。重试边回到等待状态，不重复绘制整个状态链。',
  er:'实体框内区分属性、主键和外键；关系连接到正确实体，基数与作者描述一致，不用流程箭头代替实体关系。',
  boxplot:'盒须图的中位数、四分位数、须和离群点必须有作者数据依据；不能自行造出分布、样本量或显著性。',
  heatmap:'矩阵的行、列、单元格必须一一对应，色阶范围、数值和颜色一致，清晰显示必要的色标。',
  bar:'柱形图数值编码必须准确，数值轴从零开始，不能用立体效果或透视夸大差异。',
  line:'折线图按作者给出的数据点和顺序连线，不添加未给出的平滑趋势、误差区间或预测点。'
 };
 if(exact[type])rules.push(exact[type]);
 if(category==='simulation')rules.push('没有边界条件、材料参数和计算结果时，只画物理对象、边界与计算流程示意，不伪造有限元云图、应力峰值、热场或实验验证结果。');
 if(category==='optics')rules.push('光路的元件顺序、入射出射方向、透镜和反射面要准确，虚实光线用不同线型，未提供条件时不编造焦距、效率或成像质量。');
 if(category==='statistics'||category==='machine-learning')rules.push('统计或机器学习图的曲线与矩阵必须来自作者明确提供的值；控制图的观测点、中心线、上限、下限分别按给定值定位，不重新发明控制限。');
 if(category==='chemistry'||category==='biomedicine')rules.push('机理图明确区分对象与过程，箭头和激活/抑制符号按作者给定关系绘制；不编造化学键、分子构型、蛋白三维结构或显微照片。');
 if(category==='electronics'||category==='automation'||category==='engineering')rules.push('技术原理图采用清晰的标准符号与连接点。必须区分连接和跨越，器件方向、极性、供电和地连接一致。缺少工程参数时只表达给定概念，不伪造仿真波形或制造尺寸。');
 if(category==='geography')rules.push('地理分析流程和图层关系要准确；没有原始遥感影像、地理边界或栅格时仅画处理流程，不能生成看似实测的地图或变化检测结果。');
 if(category==='rendering'||category==='architecture-planning')rules.push('空间或部件关系优先，采用简洁轴测或剖视表达；仅在表达结构时使用轻微明暗。分镜保持同一物体的拓扑与部件数量，不添加未经给定的尺寸。');
 return rules.join('\n');
}
